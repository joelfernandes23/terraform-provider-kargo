var (
	_ resource.Resource                = &ProjectConfigResource{}
	_ resource.ResourceWithImportState = &ProjectConfigResource{}
)

type ProjectConfigResource struct {
	client client.KargoClient
}

type ProjectConfigResourceModel struct {
	Project           types.String                `tfsdk:"project"`
	ID                types.String                `tfsdk:"id"`
	PromotionPolicies []ProjectConfigPolicyModel  `tfsdk:"promotion_policy"`
	WebhookReceivers  []ProjectConfigWebhookModel `tfsdk:"webhook_receiver"`
	WebhookEndpoints  types.List                  `tfsdk:"webhook_endpoint"`
}

type ProjectConfigPolicyModel struct {
	StageSelector        *ProjectConfigSelectorModel `tfsdk:"stage_selector"`
	AutoPromotionEnabled types.Bool                  `tfsdk:"auto_promotion_enabled"`
}

type ProjectConfigSelectorModel struct {
	Name             types.String                        `tfsdk:"name"`
	MatchLabels      types.Map                           `tfsdk:"match_labels"`
	MatchExpressions []ProjectConfigMatchExpressionModel `tfsdk:"match_expression"`
}

type ProjectConfigMatchExpressionModel struct {
	Key      types.String `tfsdk:"key"`
	Operator types.String `tfsdk:"operator"`
	Values   types.List   `tfsdk:"values"`
}

type ProjectConfigWebhookModel struct {
	Name            types.String         `tfsdk:"name"`
	Type            types.String         `tfsdk:"type"`
	SecretName      types.String         `tfsdk:"secret_name"`
	VirtualRepoName types.String         `tfsdk:"virtual_repo_name"`
	GenericActions  jsontypes.Normalized `tfsdk:"generic_actions"`
}

type ProjectConfigEndpointModel struct {
	Name types.String `tfsdk:"name"`
	Path types.String `tfsdk:"path"`
	URL  types.String `tfsdk:"url"`
}

func NewProjectConfigResource() resource.Resource {
	return &ProjectConfigResource{}
}

func (r *ProjectConfigResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_project_config"
}

